# Tuples

score = (90, 80, 70, 60, 50) # Note: Parentheses () are used for tuples, while square brackets [] are for lists

print(len(score)) # Get the length (number of elements) of the tuple
print(score[0:3]) # Get the first 3 elements (from index 0 up to 2)

# The operations above are similar to lists, but tuples are IMMUTABLE (elements cannot be modified).
# This is useful for preventing data from being accidentally changed in your program.